package main

import (
	"errors"
	"fmt"
	"go/doc"
	"go/parser"
	"go/token"
	"io/fs"
	"path"
	"slices"
	"strconv"
	"strings"
)

// pkgInfo is one row of the map.
type pkgInfo struct {
	dir     string // module-relative, slash-separated
	layer   string // from the layers table; "-" is build tooling
	purpose string // first sentence of the doc.go package comment
}

// layerRow is the part of a layers-table row the map shows. The budget tool
// validates the whole table; this reader only needs package and layer.
type layerRow struct {
	layer string
	pkg   string // a trailing "/*" covers the whole tree
}

// describe builds a row per package and reports every package it cannot
// describe at once, so one run lists all missing doc.go files.
func describe(fsys fs.FS, dirs []string, rows []layerRow) ([]pkgInfo, error) {
	var pkgs []pkgInfo
	var errs []error
	for _, dir := range dirs {
		purpose, err := synopsis(fsys, dir)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		layer, ok := layerFor(rows, dir)
		if !ok {
			errs = append(errs, fmt.Errorf("%s has no row in the layers table (docs/architecture.md §3)", dir))
			continue
		}
		pkgs = append(pkgs, pkgInfo{dir: dir, layer: layer, purpose: purpose})
	}
	return pkgs, errors.Join(errs...)
}

// synopsis returns the first sentence of the package comment in dir/doc.go.
// Only doc.go counts: AGENTS.md puts the reason a package exists there.
func synopsis(fsys fs.FS, dir string) (string, error) {
	name := path.Join(dir, "doc.go")
	src, err := fs.ReadFile(fsys, name)
	if err != nil {
		return "", fmt.Errorf("%s: every package needs a doc.go saying why it exists: %w", dir, err)
	}
	f, err := parser.ParseFile(token.NewFileSet(), name, src, parser.PackageClauseOnly|parser.ParseComments)
	if err != nil {
		return "", fmt.Errorf("parse %s: %w", name, err)
	}
	if f.Doc == nil {
		return "", fmt.Errorf("%s has no package comment", name)
	}
	s := new(doc.Package).Synopsis(f.Doc.Text())
	if s == "" {
		return "", fmt.Errorf("%s: the package comment has no first sentence", name)
	}
	return s, nil
}

// parseLayers reads package and layer from the one ```layers block.
func parseLayers(text string) ([]layerRow, error) {
	_, rest, found := strings.Cut(text, "```layers")
	block, _, closed := strings.Cut(rest, "```")
	if !found || !closed {
		return nil, errors.New("no closed ```layers block")
	}
	var rows []layerRow
	for _, line := range strings.Split(block, "\n") {
		code, _, _ := strings.Cut(line, "#")
		f := strings.Fields(code)
		if len(f) == 0 {
			continue
		}
		if len(f) < 2 {
			return nil, fmt.Errorf("layers row %q: want \"<layer|-> <package> ...\"", strings.TrimSpace(line))
		}
		rows = append(rows, layerRow{layer: f[0], pkg: f[1]})
	}
	return rows, nil
}

func layerFor(rows []layerRow, dir string) (string, bool) {
	for _, r := range rows {
		tree, wild := strings.CutSuffix(r.pkg, "/*")
		if r.pkg == dir || wild && strings.HasPrefix(dir, tree+"/") {
			return r.layer, true
		}
	}
	return "", false
}

const mapHeader = `# Package map

Generated by ` + "`make map`" + ` (internal/tools/pkgmap) from ` + "`go list ./...`" + `, the first sentence of each package's ` + "`doc.go`" + ` and the layers table in [architecture.md §3](architecture.md#3-components-and-layers). Do not edit it by hand: ` + "`make check`" + ` fails when it is stale. A package may import only lower layers that its row in the table lists; ` + "`-`" + ` is build tooling, never imported by the product.

| Layer | Package | Purpose |
|---|---|---|
`

// render sorts by layer, build tooling last, then by path, so the output
// depends only on the packages and not on go list's order.
func render(pkgs []pkgInfo) []byte {
	sorted := slices.Clone(pkgs)
	slices.SortFunc(sorted, func(a, b pkgInfo) int {
		if c := layerRank(a.layer) - layerRank(b.layer); c != 0 {
			return c
		}
		return strings.Compare(a.dir, b.dir)
	})
	var b strings.Builder
	b.WriteString(mapHeader)
	for _, p := range sorted {
		fmt.Fprintf(&b, "| %s | [`%s`](%s) | %s |\n", p.layer, p.dir, path.Join("..", p.dir, "doc.go"), cell(p.purpose))
	}
	return []byte(b.String())
}

// layerRank orders numeric layers ascending and anything else after them.
func layerRank(layer string) int {
	n, err := strconv.Atoi(layer)
	if err != nil || n < 0 {
		return 1 << 20
	}
	return n
}

// cell keeps a sentence inside its table cell.
func cell(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ").Replace(s)
}
