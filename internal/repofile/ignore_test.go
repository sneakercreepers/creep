package repofile

import (
	"strings"
	"testing"
)

const routeSrc = "from flask import Flask\napp = Flask(__name__)\n@app.get('/a')\ndef a():\n    db.execute(q)\n"

func TestIgnoreReason(t *testing.T) {
	longLine := strings.Repeat("var a=1;", 200)
	cases := []struct {
		name, path, src string
		want            Ignored
	}{
		{"plain app", "app/views.py", routeSrc, 0},
		{"vendor dir", "vendor/lib/app.py", routeSrc, IgnoredVendor},
		{"nested node_modules", "web/node_modules/x/index.js", "", IgnoredVendor},
		{"windows separators", `web\node_modules\x\index.js`, "", IgnoredVendor},
		{"case-insensitive dir", "Lib/Site-Packages/flask/app.py", routeSrc, IgnoredVendor},
		{"virtualenv", ".venv/lib/python3.12/m.py", "", IgnoredVendor},
		{"vendor as file name only", "src/vendor.py", routeSrc, 0},
		{"vendor-like dir name", "src/vendors/app.py", routeSrc, 0},
		{"dot-slash vendor", "./vendor/x.py", routeSrc, IgnoredVendor},
		{"vendor_utils file", "src/vendor_utils.py", routeSrc, 0},
		{"go-style marker", "api/models.py", "# Code generated by tool. DO NOT EDIT.\n" + routeSrc, IgnoredGenerated},
		{"go-style marker CRLF", "api/models.py", "# Code generated by x. DO NOT EDIT.\r\n" + routeSrc, IgnoredGenerated},
		{"marker after BOM", "api/m.py", "\xef\xbb\xbf# @generated\n" + routeSrc, IgnoredGenerated},
		{"protoc marker after coding line", "api/x_pb2.py", "# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n", IgnoredGenerated},
		{"@generated in block comment", "gen/client.ts", "/**\n * @generated\n */\nexport {}\n", IgnoredGenerated},
		{"@generated after shebang", "gen/c.js", "#!/usr/bin/env node\n// @generated by relay\n", IgnoredGenerated},
		{"loose do-not-modify", "gen/c.js", "// This file was generated. Do not modify.\n", 0},
		{"not generated, do not edit", "app.py", "#!/usr/bin/env python\n# This module is not generated. Do not edit lightly.\n" + routeSrc, 0},
		{"@generated mid-comment", "app.py", "# see the @generated docs\n" + routeSrc, 0},
		{"js mention of generated dir", "app.js", "// Wrapper for generated/ code; do not edit files in generated/\n", 0},
		{"marker in a triple-quoted string", "app.py", "x = '''\n# Code generated by x. DO NOT EDIT.\n'''\n" + routeSrc, 0},
		{"marker in a docstring", "app.py", "\"\"\"Wraps the API.\n\n* @generated\n\"\"\"\n" + routeSrc, 0},
		{"marker after code", "app.py", "import os\n# @generated\n" + routeSrc, 0},
		{"trailing comment marker", "app.py", "x = 1 # @generated\n" + routeSrc, 0},
		{"js block closed then code", "a.js", "/* lic */ var x = 1;\n// @generated\n", 0},
		{"python star line is code", "a.py", "*a, b = c\n# @generated\n", 0},
		{"marker past the head", "app.py", strings.Repeat("# pad\n", 200) + "# Code generated x DO NOT EDIT.\n", 0},
		{"marker in a string, not a comment", "app.py", "s = '@generated'\n" + routeSrc, 0},
		{"generated without do-not-edit", "app.py", "# Generated by Django 4.2\n" + routeSrc, 0},
		// A .min name alone is the author's say-so (pentest P4): parsed.
		{"min.js name, short lines", "static/app.min.js", "a()\n", 0},
		{"-min.js name, short lines", "static/app-min.js", "a()\n", 0},
		{"min.js name, long lines", "static/app.min.js", longLine, IgnoredMinified},
		{"long-line script", "static/bundle.js", longLine, IgnoredMinified},
		{"long-line typescript", "static/bundle.ts", longLine + "\n" + longLine, IgnoredMinified},
		{"minimal.js is not minified", "static/minimal.js", "a()\n", 0},
		{"one long line pads readable code", "static/app.js", longLine + "\n" + strings.Repeat("app.get('/x', h);\n", 100), 0},
		{"short long-line script", "static/tiny.js", "var a=1;var b=2;", 0},
		{"long python line is parsed", "app.py", "x = '" + strings.Repeat("a", 4000) + "'\n", 0},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, err := IgnoreReason(c.path, []byte(c.src))
			if err != nil || got != c.want {
				t.Errorf("IgnoreReason(%q) = %s, %v, want %s", c.path, got, err, c.want)
			}
		})
	}
}

// TestIgnoreReasonNeedsRepoRelativePath: directories above the repository
// root (a checkout under /home/u/vendor/) must not decide what is skipped.
func TestIgnoreReasonNeedsRepoRelativePath(t *testing.T) {
	for _, name := range []string{"/home/u/vendor/proj/app.py", `C:\src\vendor\app.py`, "C:/x/app.py", `\\host\share\a.py`, "../vendor/a.py", "a/../../b.py", "", "."} {
		if _, err := IgnoreReason(name, []byte(routeSrc)); err == nil {
			t.Errorf("IgnoreReason(%q) accepted", name)
		}
	}
}

func TestIgnoredString(t *testing.T) {
	for r, want := range map[Ignored]string{0: "none", IgnoredVendor: "vendor", IgnoredGenerated: "generated", IgnoredMinified: "minified", 9: "unknown"} {
		if r.String() != want {
			t.Errorf("Ignored(%d) = %s, want %s", r, r, want)
		}
	}
}

// BenchmarkIgnoreReason: the check reads a bounded head plus one byte count,
// so it stays linear on a large file.
func BenchmarkIgnoreReason(b *testing.B) {
	src := []byte(strings.Repeat("x = 1\n", 1<<18))
	b.SetBytes(int64(len(src)))
	for b.Loop() {
		if _, err := IgnoreReason("pkg/deep/app.js", src); err != nil {
			b.Fatal(err)
		}
	}
}

// TestVendorEvidence (pentest P4, #213): a vendor directory is believed
// only through its package manager's mark, with exact case; the mark names
// its tree whatever the file's language. Go and PHP vendor trees have none,
// and everything else has no evidence and is read.
func TestVendorEvidence(t *testing.T) {
	cases := map[string]string{ // "" means no evidence can vouch for it
		".venv/lib/python3.12/site-packages/x.py": ".venv/pyvenv.cfg",
		"services/api/venv/lib/x.py":              "services/api/venv/pyvenv.cfg",
		"node_modules/app/app.js":                 "node_modules/app/package.json",
		"web/node_modules/@scope/pkg/lib/i.ts":    "web/node_modules/@scope/pkg/package.json",
		"node_modules/a/node_modules/b/i.js":      "node_modules/a/package.json",
		"venv/Lib/site-packages/m/_speedups.c":    "venv/pyvenv.cfg",
		"node_modules/node-gyp/lib/Find-VS.cs":    "node_modules/node-gyp/package.json",
		"node_modules/node-gyp/gyp/pylib/gyp.py":  "node_modules/node-gyp/package.json",
		"venv/web/App.vue":                        "venv/pyvenv.cfg",
		"vendor/github.com/x/y/z.go":              "",
		"vendor/modules.txt":                      "",
		"lib/vendor/acme/a.php":                   "",
		"vendor/acme/a.php":                       "",
		"node_modules/app.js":                     "",
		"node_modules/@scope/app.js":              "",
		"venv":                                    "",
		"vendor/lib/app.py":                       "",
		"VENDOR/x.go":                             "",
		"Node_Modules/app/app.js":                 "",
		"VENV/lib/x.py":                           "",
		"third_party/svc/app.py":                  "",
		"site-packages/x.py":                      "",
		"app.py":                                  "",
		"../node_modules/a/b.js":                  "",
		"/node_modules/a/b.js":                    "",
		"":                                        "",
	}
	for name, want := range cases {
		got, ok := VendorEvidence(name)
		if ok != (want != "") || got != want && ok {
			t.Errorf("VendorEvidence(%q) = %q, %v; want %q", name, got, ok, want)
		}
	}
}
