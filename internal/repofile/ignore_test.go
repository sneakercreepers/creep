package repofile

import (
	"runtime"
	"strings"
	"testing"
)

const routeSrc = "from flask import Flask\napp = Flask(__name__)\n@app.get('/a')\ndef a():\n    db.execute(q)\n"

// TestIgnoreReason (#366): the marks read bytes only, so they hold for any
// language and comment syntax, and no directory or file name is a mark.
func TestIgnoreReason(t *testing.T) {
	longLine := strings.Repeat("var a=1;", 200)
	cases := []struct {
		name, path, src string
		want            Ignored
	}{
		{"plain app", "app/views.py", routeSrc, 0},
		{"a dependency-like directory is no mark", "vendor/lib/app.py", routeSrc, 0},
		{"dot-slash path", "./vendor/x.py", routeSrc, 0},
		{"code generated header", "api/models.py", "# Code generated by tool. DO NOT EDIT.\n" + routeSrc, IgnoredGenerated},
		{"CRLF header", "api/models.py", "# Code generated by x. DO NOT EDIT.\r\n" + routeSrc, IgnoredGenerated},
		{"marker after BOM", "api/m.py", "\xef\xbb\xbf# @generated\n" + routeSrc, IgnoredGenerated},
		{"compiler header after a coding line", "api/x_pb2.py", "# -*- coding: utf-8 -*-\n# Generated by the compiler.  DO NOT EDIT!\n", IgnoredGenerated},
		{"@generated in a block comment", "gen/client.ts", "/**\n * @generated\n */\nexport {}\n", IgnoredGenerated},
		{"do not modify", "gen/c.js", "// This file was generated. Do not modify.\n", IgnoredGenerated},
		{"dash comment", "gen/q.sql", "-- generated by sqlc, DO NOT EDIT\n", IgnoredGenerated},
		{"semicolon comment", "gen/x.zig", ";; @generated\n", IgnoredGenerated},
		{"markup comment", "gen/x.nim", "<!-- Generated file: do not edit -->\n", IgnoredGenerated},
		{"fifth line", "gen/x.ml", "(*\n *\n *\n *\n * @generated *)\n", IgnoredGenerated},
		{"sixth line is past the head", "gen/x.ml", "a\nb\nc\nd\ne\n// @generated\n", 0},
		{"marker past the head bytes", "app.py", strings.Repeat("#", generatedHeadBytes) + "\n# @generated\n" + strings.Repeat("x = 1\n", 400), 0},
		{"@generated inside a word", "app.py", "# x@generatedy\n" + routeSrc, 0},
		{"generated without do-not-edit", "app.py", "# Generated by a framework 4.2\n" + routeSrc, 0},
		{"do not edit without generated", "app.py", "# do not edit lightly\n" + routeSrc, 0},
		// A .min name alone is the author's say-so (pentest P4): no mark.
		{"min name, short lines", "static/app.min.js", "a()\n", 0},
		{"min name, long lines", "static/app.min.js", longLine, IgnoredMinified},
		{"long lines in any language", "lib/x.nim", longLine, IgnoredMinified},
		{"two long lines", "static/bundle.ts", longLine + "\n" + longLine, IgnoredMinified},
		{"one long line pads readable code", "static/app.js", longLine + "\n" + strings.Repeat("app.get('/x', h);\n", 100), 0},
		{"short long-line file", "static/tiny.js", "var a=1;var b=2;", 0},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, err := IgnoreReason(c.path, []byte(c.src))
			if err != nil || got != c.want {
				t.Errorf("IgnoreReason(%q) = %s, %v, want %s", c.path, got, err, c.want)
			}
		})
	}
}

// TestIgnoreReasonNeedsRepoRelativePath: a name outside the repository is
// refused, whatever its bytes.
func TestIgnoreReasonNeedsRepoRelativePath(t *testing.T) {
	for _, name := range []string{"/home/u/vendor/proj/app.py", `C:\src\vendor\app.py`, "C:/x/app.py", "c:x.py", "../vendor/a.py", "a/../../b.py", "", "."} {
		if _, err := IgnoreReason(name, []byte(routeSrc)); err == nil {
			t.Errorf("IgnoreReason(%q) accepted", name)
		}
	}
}

// TestIgnoreReasonUNCName: a UNC path is absolute on Windows; elsewhere it
// is one file name at the root.
func TestIgnoreReasonUNCName(t *testing.T) {
	got, err := IgnoreReason(`\\host\share\vendor\a.py`, []byte(routeSrc))
	if runtime.GOOS == "windows" {
		if err == nil {
			t.Errorf("IgnoreReason accepted a UNC path: %s", got)
		}
		return
	}
	if err != nil || got != 0 {
		t.Errorf("IgnoreReason = %s, %v, want no mark", got, err)
	}
}

func TestIgnoredString(t *testing.T) {
	for r, want := range map[Ignored]string{0: "none", IgnoredGenerated: "generated", IgnoredMinified: "minified", 9: "unknown"} {
		if r.String() != want {
			t.Errorf("Ignored(%d) = %s, want %s", r, r, want)
		}
	}
}

// BenchmarkIgnoreReason: the check reads a bounded head plus one byte count,
// so it stays linear on a large file.
func BenchmarkIgnoreReason(b *testing.B) {
	src := []byte(strings.Repeat("x = 1\n", 1<<18))
	b.SetBytes(int64(len(src)))
	for b.Loop() {
		if _, err := IgnoreReason("pkg/deep/app.js", src); err != nil {
			b.Fatal(err)
		}
	}
}
