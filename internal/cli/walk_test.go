const flaskRoute = "from flask import Flask, request\nimport os\napp = Flask(__name__)\n\n@app.route(\"/x\")\ndef x():\n    return str(os.system(request.args[\"c\"]))\n"

// Acceptance (#175, auditor note on #189): a name static refuses, such as
// a:b.py (read as a drive letter), is listed as not evaluated and the walk
// goes on; so is every other file static cannot take in full.
func TestAddFile(t *testing.T) {
	ctx := context.Background()
	p, err := static.NewParser(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer p.Close(ctx)
	tests := []struct {
		name string
		lang static.Language
		src  string
		want report.SkipReason // "" when extracted in full
	}{
		{"a:b.py", static.Python, flaskRoute, report.SkipInvalidPath},
		{"C:/abs.py", static.Python, flaskRoute, report.SkipInvalidPath},
		{"../up.py", static.Python, flaskRoute, report.SkipInvalidPath},
		{`web\app.py`, static.Python, flaskRoute, report.SkipInvalidPath}, // #177: static reads it, the report refuses it
		{"./app.py", static.Python, flaskRoute, report.SkipInvalidPath},
		{"app.py", static.Python, flaskRoute, ""},
		{"broken.py", static.Python, "def f(:\n", report.SkipSyntaxError},
		{"gen.py", static.Python, "# Code generated by protoc. DO NOT EDIT.\nimport os\n", report.SkipGenerated},
		{"site-packages/x.py", static.Python, "import os\n", report.SkipVendor},
		{"vendor/views.py", static.Python, flaskRoute, ""}, // a route: the vendor path is not believed
		{"web/app.min.js", static.JavaScript, "x()", ""},
		{"web/bundle.js", static.JavaScript, strings.Repeat("x();", 400), report.SkipMinified},
		{"web/app.js", static.JavaScript, "x()", ""},
		{"web/app.ts", static.TypeScript, "let x: number = 1\n", ""},
		{"odd.txt", static.Language(0), "x", report.SkipUnsupported},
	}
	ex := static.NewExtractor()
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, gap := addFile(ctx, ex, p, tt.name, tt.lang, []byte(tt.src))
			if got != tt.want || gap != (tt.want != "") {
				t.Fatalf("addFile = %q, %v; want %q", got, gap, tt.want)
			}
		})
	}
	if routes := len(ex.Graph().Routes); routes != 2 {
		t.Fatalf("%d routes extracted, want app.py's and vendor/views.py's", routes)
	}
}

// Through the CLI on a file system that allows the names: a:b.py and
// web\app.py (#177) are listed, the run is incomplete (exit 4) and the rest
// of the repository is scanned.
func TestScanListsRefusedName(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("a:b.py names an alternate data stream on Windows; TestAddFile covers the name")
	}
	cfg := scanRepo(t, map[string]string{"app.py": "@flask", "a:b.py": flaskRoute, `web\app.py`: flaskRoute}, "")
	code, out, _ := runScanWith(fakeDeps(&fakeModel{}, calibrate.TierM), "scan", "--config", cfg)
	if code != exitcode.Incomplete || !strings.Contains(out, "a:b.py  invalid_path") || !strings.Contains(out, "reason invalid_path") {
		t.Fatalf("exit %d\n%s", code, out)
	}
	rep, err := readLastReport()
	if err != nil || len(rep.Findings) != 4 {
		t.Fatalf("report: %v, findings %+v", err, rep)
	}
}

// Links and special files with a source extension are listed, not
// followed: a link could point outside the repository.
func TestWalkListsLinks(t *testing.T) {
	isolateUserConfig(t)
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "real.py"), []byte("x = 1\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(filepath.Join(dir, "real.py"), filepath.Join(dir, "link.py")); err != nil {
		t.Skipf("no symlinks here: %v", err)
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		t.Fatal(err)
	}
	defer root.Close()
	ctx := context.Background()
	p, err := static.NewParser(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer p.Close(ctx)
	rs, err := walkRepo(ctx, root, p)
	if err != nil {
		t.Fatal(err)
	}
	want := []report.NotEvaluated{{Path: "link.py", Reason: report.SkipNotRegular}}
	if len(rs.gaps) != 1 || rs.gaps[0] != want[0] {
		t.Fatalf("gaps = %+v, want %+v", rs.gaps, want)
	}
}

// #14 (#179 audit): a file static cut at a cap (Truncated, also set for a
// Route.Partial) or parsed with errors is listed as partial, never clean.
func TestPartialFile(t *testing.T) {
	tests := []struct {
		file static.File
		want report.SkipReason
	}{
		{static.File{}, ""},
		{static.File{Truncated: true}, report.SkipTruncated},
		{static.File{SyntaxError: true}, report.SkipSyntaxError},
		{static.File{Truncated: true, SyntaxError: true}, report.SkipTruncated},
	}
	for _, tt := range tests {
		got, gap := fileOutcome(static.Graph{Files: []static.File{{}, tt.file}})
		if got != tt.want || gap != (tt.want != "") || got.ByDesign() {
			t.Errorf("fileOutcome(%+v) = %q, %v; want %q", tt.file, got, gap, tt.want)
		}
		if gap && incompleteReason("", nil, []report.NotEvaluated{{Path: "a.py", Reason: got}}) != string(got) {
			t.Errorf("a %s file does not make the run incomplete", got)
		}
	}
}

// Only the root's .git and .creep are skipped: a nested folder with either
// name is scanned, so a repository cannot hide a route behind the name.
func TestWalkSkipsOnlyRootStateDirs(t *testing.T) {
	dir := t.TempDir()
	for _, name := range []string{".creep/x.py", ".git/hooks/x.py", "pkg/.creep/routes.py", "pkg/.git/routes.py"} {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(flaskRoute), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		t.Fatal(err)
	}
	defer root.Close()
	ctx := context.Background()
	p, err := static.NewParser(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer p.Close(ctx)
	rs, err := walkRepo(ctx, root, p)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"pkg/.creep/routes.py", "pkg/.git/routes.py"}
	if len(rs.locs.Files) != len(want) || rs.locs.Files[0] != want[0] || rs.locs.Files[1] != want[1] || len(rs.graph.Routes) != 2 {
		t.Fatalf("scanned %v with %d routes, want %v", rs.locs.Files, len(rs.graph.Routes), want)
	}
}

// Acceptance (#175, #199 audit): planner.ErrInput (here a sink naming an
// unknown route; in the wild a graph over 2^20 routes) fails the scan
// closed: every sink is not evaluated, no class is covered and the exit
// code is 4, never a clean result.
func TestPlannerRejectionFailsClosed(t *testing.T) {
	rs := repoScan{
		graph: static.Graph{
			Files:  []static.File{{ID: 0, Language: static.Python}},
			Routes: []static.Route{{ID: 0, File: 0, Methods: static.MethodGet}},
			Sinks:  []static.Sink{{ID: 0, Route: 7, Kind: static.SinkShell, DynamicArg: true}},
		},
		locs: static.Locations{Files: []string{"app.py"}, Routes: []static.RouteLocation{{Line: 1}}, Sinks: []static.SinkLocation{{Line: 2}}},
	}
	findings := []report.Finding{{ID: "sink-0", Class: "command_injection", Status: report.StatusNotEvaluated, Path: "app.py", Line: 2}}
	_, err := planSinks(rs, planner.TierM, planner.Budget{Tokens: 1 << 20, StepTokens: 1}, findings)
	if !errors.Is(err, planner.ErrInput) {
		t.Fatalf("planSinks err = %v, want planner.ErrInput", err)
	}
	res := rejectedScan(findings, nil)
	reason := incompleteReason(res.stop, res.findings, res.gaps)
	classes := classCoverage(coverageInput{findings: res.findings, gapped: true, planned: res.planned})
	if reason != reasonPlannerRejected || res.findings[0].Reason != reasonPlannerRejected {
		t.Fatalf("reason %q, finding %+v", reason, res.findings[0])
	}
	for _, c := range classes {
		if c.Status != report.ClassNotEvaluated {
			t.Errorf("class %s is %s after a planner rejection", c.Class, c.Status)
		}
	}
	if exitcode.ForReport(reason != "", false) != exitcode.Incomplete {
		t.Fatal("planner rejection does not exit 4")
	}
}
