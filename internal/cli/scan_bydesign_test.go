const (
	generatedHeader = "# Code generated by hand. DO NOT EDIT.\n"
	unsupported     = string(report.SkipUnsupported)
	syntaxError     = string(report.SkipSyntaxError)
	tooLarge        = string(report.SkipTooLarge)
)

type byDesignCase struct {
	name       string
	files      map[string]string // "@flask", "@express" and "@express-hidden" after a prefix are the vulnerable test apps
	links      map[string]string // link name -> target, both repo-relative
	wantCode   int
	wantReason string
	want       []string // lines the output must hold
}

// Regression (pentest P4, #213, tester bypasses on #231 and #205): code the
// author only declares vendor, generated or minified is evaluated. A vendor
// name without its package manager's mark, in exact case, is read like
// first-party code; any declared skip is believed only for a file that holds
// no route; an ungrammared file under a vendor name is a gap. None of these
// exits 0 with every class covered. The by-design cases keep a first-party
// route (helloRoute), since without one the run is no_routes, and the text
// names what no class covers.
func TestScanDoesNotTrustDeclaredSkips(t *testing.T) {
	padding := strings.Repeat("/", 4000) + "\n"
	dense := strings.Repeat("var a=1;", 200) + "\n"
	tests := []byDesignCase{
		{name: "root third_party", files: map[string]string{"third_party/app.py": "@flask"}, wantCode: exitcode.GateExceeded, want: []string{"probable  sqli  third_party/app.py:"}},
		{name: "root venv without pyvenv.cfg", files: map[string]string{"venv/app.py": "@flask"}, wantCode: exitcode.GateExceeded, want: []string{"probable  sqli  venv/app.py:"}},
		{name: "root VENDOR", files: map[string]string{"VENDOR/app.py": "@flask"}, wantCode: exitcode.GateExceeded, want: []string{"probable  sqli  VENDOR/app.py:"}},
		{name: "root site-packages", files: map[string]string{"site-packages/app.py": "@flask"}, wantCode: exitcode.GateExceeded, want: []string{"probable  sqli  site-packages/app.py:"}},
		{name: "nested vendor", files: map[string]string{"app/vendor/app.py": "@flask"}, wantCode: exitcode.GateExceeded, want: []string{"probable  sqli  app/vendor/app.py:"}},
		{name: "node_modules without package.json", files: map[string]string{"node_modules/app/app.js": "@express"}, wantCode: exitcode.GateExceeded, want: []string{"probable  command_injection  node_modules/app/app.js:"}},
		{name: "mixed-case Node_Modules with package.json", files: map[string]string{"Node_Modules/app/package.json": "{}", "Node_Modules/app/app.js": "@express"}, wantCode: exitcode.GateExceeded, want: []string{"probable  command_injection  Node_Modules/app/app.js:"}},
		{name: "mixed-case VENV with pyvenv.cfg", files: map[string]string{"VENV/pyvenv.cfg": "home = /usr\n", "VENV/app.py": "@flask"}, wantCode: exitcode.GateExceeded, want: []string{"probable  sqli  VENV/app.py:"}},
		{name: "python under node_modules", files: map[string]string{"src/node_modules/app/package.json": "{}", "src/node_modules/app/app.py": "@flask"}, wantCode: exitcode.GateExceeded, want: []string{"probable  sqli  src/node_modules/app/app.py:"}},
		{name: "generated header", files: map[string]string{"app.py": generatedHeader + "@flask"}, wantCode: exitcode.GateExceeded, want: []string{"probable  sqli  app.py:"}},
		{name: "padded with one long line", files: map[string]string{"app.js": padding + "@express"}, wantCode: exitcode.GateExceeded, want: []string{"probable  command_injection  app.js:"}},
		{name: "min.js name", files: map[string]string{"app.min.js": "@express"}, wantCode: exitcode.GateExceeded, want: []string{"probable  command_injection  app.min.js:"}},
		{name: "go under nested vendor", files: map[string]string{"main.py": helloRoute, "src/vendor/x.go": "package x\n"}, wantCode: exitcode.Incomplete, wantReason: unsupported, want: []string{"src/vendor/x.go  unsupported_language"}},
		{name: "go under third_party", files: map[string]string{"main.py": helloRoute, "third_party/svc/main.go": "package main\n"}, wantCode: exitcode.Incomplete, wantReason: unsupported, want: []string{"third_party/svc/main.go  unsupported_language"}},
		{name: "unproven vendor with a syntax error", files: map[string]string{"main.py": helloRoute, "vendor/lib.js": "function (\n"}, wantCode: exitcode.Incomplete, wantReason: syntaxError, want: []string{"vendor/lib.js  syntax_error"}},
		{name: "venv with pyvenv.cfg", files: map[string]string{"main.py": helloRoute, "venv/pyvenv.cfg": "home = /usr\n", "venv/lib/util.py": "def add(a, b):\n    return a + b\n"}, wantCode: exitcode.OK, want: []string{"venv/lib/util.py  vendor", "coverage excludes 1 file left out by design (vendor 1), listed above"}},
		{name: "root node_modules packages", files: map[string]string{"main.py": helloRoute, "node_modules/app/package.json": "{}", "node_modules/app/index.js": "x()\n", "node_modules/@s/b/package.json": "{}", "node_modules/@s/b/i.js": "x()\n"}, wantCode: exitcode.OK, want: []string{"node_modules/app/index.js  vendor", "node_modules/@s/b/i.js  vendor", "coverage excludes 2 files left out by design (vendor 2)"}},
		{name: "node_modules next to a nested manifest", files: map[string]string{"main.py": helloRoute, "web/package.json": "{}", "web/node_modules/app/package.json": "{}", "web/node_modules/app/index.js": "x()\n"}, wantCode: exitcode.OK, want: []string{"web/node_modules/app/index.js  vendor", "coverage excludes 1 file left out by design (vendor 1)"}},
		{name: "generated and minified, no route", files: map[string]string{"main.py": helloRoute, "api_pb2.py": generatedHeader + "import os\n", "lib.min.js": dense}, wantCode: exitcode.OK, want: []string{"api_pb2.py  generated", "lib.min.js  minified", "coverage excludes 2 files left out by design (generated 1, minified 1)"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) { runByDesignCase(t, tt) })
	}
}

// TestScanDoesNotTrustForgedMarks (#213 tester M1 and L1): a package
// manager's mark is a file the author can plant, so it never hides a route.
// A proven file that may hold one (static.MayHoldRoute) is parsed like
// first-party code: a route is evaluated, and one static cannot parse or
// that is too large is a gap. Go and PHP marks vouch for nothing. Only a
// proven file that cannot hold a route is listed unparsed, which is what
// keeps real trees with large or unparseable library files at exit 0. A
// mark counts only in exact case, on every file system.
func TestScanDoesNotTrustForgedMarks(t *testing.T) {
	bigRoute := "@express" + "\n// " + strings.Repeat("x", 1<<20) + "\n"
	bigLibrary := strings.Repeat("var a = 1;\n", 150_000)
	tests := []byDesignCase{
		{name: "root package", files: map[string]string{"main.py": helloRoute, "node_modules/app/package.json": "{}", "node_modules/app/app.js": "@express"}, wantCode: exitcode.GateExceeded, want: []string{"probable  command_injection  node_modules/app/app.js:"}},
		{name: "scoped package", files: map[string]string{"main.py": helloRoute, "node_modules/@acme/api/package.json": "{}", "node_modules/@acme/api/app.js": "@express"}, wantCode: exitcode.GateExceeded, want: []string{"probable  command_injection  node_modules/@acme/api/app.js:"}},
		{name: "nested package", files: map[string]string{"main.py": helloRoute, "src/node_modules/app/package.json": "{}", "src/node_modules/app/lib/app.js": "@express"}, wantCode: exitcode.GateExceeded, want: []string{"probable  command_injection  src/node_modules/app/lib/app.js:"}},
		{name: "require built from pieces", files: map[string]string{"main.py": helloRoute, "node_modules/app/package.json": "{}", "node_modules/app/app.js": "@express-hidden"}, wantCode: exitcode.GateExceeded, want: []string{"probable  command_injection  node_modules/app/app.js:"}},
		{name: "empty pyvenv.cfg", files: map[string]string{"main.py": helloRoute, "venv/pyvenv.cfg": "", "venv/app.py": "@flask"}, wantCode: exitcode.GateExceeded, want: []string{"probable  sqli  venv/app.py:"}},
		{name: "dot venv", files: map[string]string{"main.py": helloRoute, ".venv/pyvenv.cfg": "home = /usr\n", ".venv/app.py": "@flask"}, wantCode: exitcode.GateExceeded, want: []string{"probable  sqli  .venv/app.py:"}},
		{name: "nested venv", files: map[string]string{"main.py": helloRoute, "src/app/venv/pyvenv.cfg": "home = /usr\n", "src/app/venv/lib/app.py": "@flask"}, wantCode: exitcode.GateExceeded, want: []string{"probable  sqli  src/app/venv/lib/app.py:"}},
		{name: "go modules.txt", files: map[string]string{"main.py": helloRoute, "vendor/modules.txt": "# x\n", "vendor/app/main.go": "package main\n"}, wantCode: exitcode.Incomplete, wantReason: unsupported, want: []string{"vendor/app/main.go  unsupported_language"}},
		{name: "nested go modules.txt", files: map[string]string{"main.py": helloRoute, "src/vendor/modules.txt": "# x\n", "src/vendor/app/main.go": "package main\n"}, wantCode: exitcode.Incomplete, wantReason: unsupported, want: []string{"src/vendor/app/main.go  unsupported_language"}},
		{name: "composer.json", files: map[string]string{"main.py": helloRoute, "composer.json": "{}", "vendor/a/index.php": "<?php echo 1;\n"}, wantCode: exitcode.Incomplete, wantReason: unsupported, want: []string{"vendor/a/index.php  unsupported_language"}},
		{name: "nested composer.json", files: map[string]string{"main.py": helloRoute, "web/composer.json": "{}", "web/vendor/a/index.php": "<?php echo 1;\n"}, wantCode: exitcode.Incomplete, wantReason: unsupported, want: []string{"web/vendor/a/index.php  unsupported_language"}},
		{name: "too large with a route", files: map[string]string{"main.py": helloRoute, "node_modules/app/package.json": "{}", "node_modules/app/app.js": bigRoute}, wantCode: exitcode.Incomplete, wantReason: tooLarge, want: []string{"node_modules/app/app.js  too_large"}},
		{name: "too large library", files: map[string]string{"main.py": helloRoute, "node_modules/big/package.json": "{}", "node_modules/big/dist.js": bigLibrary}, wantCode: exitcode.OK, want: []string{"node_modules/big/dist.js  vendor"}},
		{name: "unparseable library", files: map[string]string{"main.py": helloRoute, "node_modules/lib/package.json": "{}", "node_modules/lib/flow.js": "function (\n"}, wantCode: exitcode.OK, want: []string{"node_modules/lib/flow.js  vendor"}},
		{name: "unparseable with a route token", files: map[string]string{"main.py": helloRoute, "node_modules/lib/package.json": "{}", "node_modules/lib/x.js": "require(\"express\");\nfunction (\n"}, wantCode: exitcode.Incomplete, wantReason: syntaxError, want: []string{"node_modules/lib/x.js  syntax_error"}},
		{name: "route token, no route", files: map[string]string{"main.py": helloRoute, "node_modules/express/package.json": "{}", "node_modules/express/index.js": "module.exports = require(\"./lib/express\");\n"}, wantCode: exitcode.OK, want: []string{"node_modules/express/index.js  vendor"}},
		{name: "upper-case PACKAGE.JSON", files: map[string]string{"main.py": helloRoute, "node_modules/lib/PACKAGE.JSON": "{}", "node_modules/lib/flow.js": "function (\n"}, wantCode: exitcode.Incomplete, wantReason: syntaxError, want: []string{"node_modules/lib/flow.js  syntax_error"}},
		{name: "mixed-case PyVenv.CFG", files: map[string]string{"main.py": helloRoute, "venv/PyVenv.CFG": "", "venv/broken.py": "def (:\n"}, wantCode: exitcode.Incomplete, wantReason: syntaxError, want: []string{"venv/broken.py  syntax_error"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) { runByDesignCase(t, tt) })
	}
}

// TestScanDoesNotTrustLinkedSkips: a link never proves a vendor tree or
// hides first-party code. A linked mark is no mark, a linked source file
// in a proven tree is not_regular, and a linked directory is not walked,
// so its target is read at its own path.
func TestScanDoesNotTrustLinkedSkips(t *testing.T) {
	tests := []byDesignCase{
		{
			name:  "linked package.json",
			files: map[string]string{"pkg.json": "{}", "node_modules/app/broken.js": "function (\n", "main.py": helloRoute},
			links: map[string]string{"node_modules/app/package.json": "pkg.json"}, wantCode: exitcode.Incomplete, wantReason: syntaxError,
			want: []string{"node_modules/app/broken.js  syntax_error"},
		},
		{
			name:  "linked pyvenv.cfg",
			files: map[string]string{"cfg.txt": "home = /usr\n", "venv/app.py": "@flask"},
			links: map[string]string{"venv/pyvenv.cfg": "cfg.txt"}, wantCode: exitcode.GateExceeded,
			want: []string{"probable  sqli  venv/app.py:"},
		},
		{
			name:  "linked source in a proven tree",
			files: map[string]string{"main.py": helloRoute, "real/app.txt": "@express", "node_modules/app/package.json": "{}"},
			links: map[string]string{"node_modules/app/app.js": "real/app.txt"}, wantCode: exitcode.Incomplete, wantReason: string(report.SkipNotRegular),
			want: []string{"node_modules/app/app.js  not_regular"},
		},
		{
			name:  "linked vendor directory",
			files: map[string]string{"src/app/package.json": "{}", "src/app/app.js": "@express"},
			links: map[string]string{"node_modules": "src"}, wantCode: exitcode.GateExceeded,
			want: []string{"probable  command_injection  src/app/app.js:"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) { runByDesignCase(t, tt) })
	}
}

func runByDesignCase(t *testing.T, tt byDesignCase) {
	t.Helper()
	cfg := scanRepo(t, expandApps(t, tt.files), "")
	for link, target := range tt.links {
		rel, err := filepath.Rel(filepath.Dir(filepath.FromSlash(link)), filepath.FromSlash(target))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink(rel, filepath.FromSlash(link)); err != nil {
			t.Skipf("symlinks unsupported here: %v", err)
		}
	}
	m := &fakeModel{verdict: map[string]string{"sql_injection": "vulnerable", "command_injection": "vulnerable"}}
	code, out, errOut := runScanWith(fakeDeps(m, calibrate.TierM), "scan", "--config", cfg)
	if code != tt.wantCode {
		t.Fatalf("exit %d, want %d\n%s\n%s", code, tt.wantCode, out, errOut)
	}
	for _, want := range tt.want {
		if !strings.Contains(out, want) {
			t.Errorf("output lacks %q:\n%s", want, out)
		}
	}
	if tt.wantCode == exitcode.OK && !strings.Contains(out, "coverage excludes ") {
		t.Errorf("a clean run with files left out by design does not say so:\n%s", out)
	}
	checkJSONReport(t, tt.wantReason)
}

// expandApps replaces "@flask", "@express" or "@express-hidden" (its
// require built from string pieces, so the bytes never hold "express") at
// the start of a line with the vulnerable test app.
func expandApps(t *testing.T, in map[string]string) map[string]string {
	t.Helper()
	out := make(map[string]string, len(in))
	for name, content := range in {
		prefix, rest, ok := strings.Cut(content, "@")
		if !ok {
			out[name] = content
			continue
		}
		app, tail, _ := strings.Cut(rest, "\n")
		switch app {
		case "flask", "express":
			content = prefix + testApp(t, app) + tail
		case "express-hidden":
			content = prefix + strings.Replace(testApp(t, "express"), `require("express")`, `require("ex" + "press")`, 1) + tail
		}
		out[name] = content
	}
	return out
}
