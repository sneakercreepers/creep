// TestScanDoesNotTrustLinkedSkips: a link never proves a vendor tree or
// hides first-party code. A linked mark is no mark, a linked source file
// in a proven tree is not_regular, and a linked directory is not walked,
// so its target is read at its own path.
func TestScanDoesNotTrustLinkedSkips(t *testing.T) {
	tests := []byDesignCase{
		{
			name:  "linked package.json",
			files: map[string]string{"pkg.json": "{}", "node_modules/app/broken.js": "function (\n", "main.py": helloRoute},
			links: map[string]string{"node_modules/app/package.json": "pkg.json"}, wantCode: exitcode.Incomplete, wantReason: syntaxError,
			want: []string{"node_modules/app/broken.js  syntax_error"},
		},
		{
			name:  "linked C source in a proven venv",
			files: map[string]string{"main.py": helloRoute, "venv/pyvenv.cfg": "", "src/app.c": "int main(void) { return 0; }\n"},
			links: map[string]string{"venv/app.c": "src/app.c"}, wantCode: exitcode.Incomplete, wantReason: unsupported,
			want: []string{"venv/app.c  not_regular", "src/app.c  unsupported_language"},
		},
		{
			name:  "linked pyvenv.cfg",
			files: map[string]string{"cfg.txt": "home = /usr\n", "venv/app.py": "@flask"},
			links: map[string]string{"venv/pyvenv.cfg": "cfg.txt"}, wantCode: exitcode.GateExceeded,
			want: []string{"probable  sqli  venv/app.py:"},
		},
		{
			name:  "linked source in a proven tree",
			files: map[string]string{"main.py": helloRoute, "real/app.txt": "@express", "node_modules/app/package.json": "{}"},
			links: map[string]string{"node_modules/app/app.js": "real/app.txt"}, wantCode: exitcode.Incomplete, wantReason: string(report.SkipNotRegular),
			want: []string{"node_modules/app/app.js  not_regular"},
		},
		{
			name:  "linked vendor directory",
			files: map[string]string{"src/app/package.json": "{}", "src/app/app.js": "@express"},
			links: map[string]string{"node_modules": "src"}, wantCode: exitcode.GateExceeded,
			want: []string{"probable  command_injection  src/app/app.js:"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) { runByDesignCase(t, tt) })
	}
}

func runByDesignCase(t *testing.T, tt byDesignCase) {
	t.Helper()
	cfg := scanRepo(t, expandApps(t, tt.files), "")
	for link, target := range tt.links {
		rel, err := filepath.Rel(filepath.Dir(filepath.FromSlash(link)), filepath.FromSlash(target))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink(rel, filepath.FromSlash(link)); err != nil {
			t.Skipf("symlinks unsupported here: %v", err)
		}
	}
	m := &fakeModel{verdict: map[string]string{"sql_injection": "vulnerable", "command_injection": "vulnerable"}}
	code, out, errOut := runScanWith(fakeDeps(m, calibrate.TierM), "scan", "--config", cfg)
	if code != tt.wantCode {
		t.Fatalf("exit %d, want %d\n%s\n%s", code, tt.wantCode, out, errOut)
	}
	for _, want := range tt.want {
		if !strings.Contains(out, want) {
			t.Errorf("output lacks %q:\n%s", want, out)
		}
	}
	if tt.wantCode == exitcode.OK && !strings.Contains(out, "coverage excludes ") {
		t.Errorf("a clean run with files left out by design does not say so:\n%s", out)
	}
	checkJSONReport(t, tt.wantReason)
}

// expandApps replaces "@flask", "@express" or "@express-hidden" (its
// require built from string pieces, so the bytes never hold "express") at
// the start of a line with the vulnerable test app.
func expandApps(t *testing.T, in map[string]string) map[string]string {
	t.Helper()
	out := make(map[string]string, len(in))
	for name, content := range in {
		prefix, rest, ok := strings.Cut(content, "@")
		if !ok {
			out[name] = content
			continue
		}
		app, tail, _ := strings.Cut(rest, "\n")
		switch app {
		case "flask", "express":
			content = prefix + testApp(t, app) + tail
		case "express-hidden":
			content = prefix + strings.Replace(testApp(t, "express"), `require("express")`, `require("ex" + "press")`, 1) + tail
		}
		out[name] = content
	}
	return out
}
