package cli

import (
	"strings"
	"testing"

	"github.com/sneakercreepers/creep/internal/calibrate"
	"github.com/sneakercreepers/creep/internal/exitcode"
)

// Regression (pentest P4, #213, tester bypasses on #231): code the author
// only declares vendor, generated or minified is evaluated. A vendor path is
// listed unread only with its package manager's mark; any other declared
// skip is believed only for a file that holds no route. The by-design cases
// keep a first-party route (helloRoute): without one the run is no_routes.
func TestScanDoesNotTrustDeclaredSkips(t *testing.T) {
	const generated = "# Code generated by hand. DO NOT EDIT.\n"
	padding := strings.Repeat("/", 4000) + "\n"
	tests := []struct {
		name       string
		files      map[string]string
		wantCode   int
		wantReason string
		want       string // a line the output must hold
	}{
		{"root third_party", map[string]string{"third_party/app.py": "@flask"}, exitcode.GateExceeded, "", "probable  sqli  third_party/app.py:"},
		{"root venv without pyvenv.cfg", map[string]string{"venv/app.py": "@flask"}, exitcode.GateExceeded, "", "probable  sqli  venv/app.py:"},
		{"root VENDOR", map[string]string{"VENDOR/app.py": "@flask"}, exitcode.GateExceeded, "", "probable  sqli  VENDOR/app.py:"},
		{"root site-packages", map[string]string{"site-packages/app.py": "@flask"}, exitcode.GateExceeded, "", "probable  sqli  site-packages/app.py:"},
		{"nested vendor", map[string]string{"app/vendor/app.py": "@flask"}, exitcode.GateExceeded, "", "probable  sqli  app/vendor/app.py:"},
		{"python under node_modules", map[string]string{"src/node_modules/app/package.json": "{}", "src/node_modules/app/app.py": "@flask"}, exitcode.GateExceeded, "", "probable  sqli  src/node_modules/app/app.py:"},
		{"generated header", map[string]string{"app.py": generated + "@flask"}, exitcode.GateExceeded, "", "probable  sqli  app.py:"},
		{"padded with one long line", map[string]string{"app.js": padding + "@express"}, exitcode.GateExceeded, "", "probable  command_injection  app.js:"},
		{"min.js name", map[string]string{"app.min.js": "@express"}, exitcode.GateExceeded, "", "probable  command_injection  app.min.js:"},
		{"venv with pyvenv.cfg", map[string]string{"main.py": helloRoute, "venv/pyvenv.cfg": "home = /usr\n", "venv/lib/app.py": "@flask"}, exitcode.OK, "", "venv/lib/app.py  vendor"},
		{"node_modules package", map[string]string{"main.py": helloRoute, "node_modules/app/package.json": "{}", "node_modules/app/app.js": "@express"}, exitcode.OK, "", "node_modules/app/app.js  vendor"},
		{"generated, no route", map[string]string{"main.py": helloRoute, "api_pb2.py": generated + "import os\n"}, exitcode.OK, "", "api_pb2.py  generated"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			files := map[string]string{}
			for name, content := range tt.files {
				prefix, app, ok := strings.Cut(content, "@")
				if ok && (app == "flask" || app == "express") {
					content = prefix + testApp(t, app)
				}
				files[name] = content
			}
			cfg := scanRepo(t, files, "")
			m := &fakeModel{verdict: map[string]string{"sql_injection": "vulnerable", "command_injection": "vulnerable"}}
			code, out, errOut := runScanWith(fakeDeps(m, calibrate.TierM), "scan", "--config", cfg)
			if code != tt.wantCode {
				t.Fatalf("exit %d, want %d\n%s\n%s", code, tt.wantCode, out, errOut)
			}
			if !strings.Contains(out, tt.want) {
				t.Errorf("output lacks %q:\n%s", tt.want, out)
			}
			checkJSONReport(t, tt.wantReason)
		})
	}
}
