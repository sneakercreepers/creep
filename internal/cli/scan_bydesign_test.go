// Regression (pentest P4, #213): code the author only declares vendor,
// generated or minified never reads as covered. A vendor-named directory
// inside first-party code or a generator header is listed and makes the
// run incomplete; a .min.js name on hand-written code is evaluated; a real
// dependency tree at the root, or node_modules, stays out by design.
func TestScanDoesNotTrustDeclaredSkips(t *testing.T) {
	const generated = "# Code generated by hand. DO NOT EDIT.\n"
	tests := []struct {
		name       string
		files      map[string]string
		wantCode   int
		wantReason string
		listed     string // a line the output must hold
	}{
		{"nested vendor", map[string]string{"app/vendor/app.py": "@flask"}, exitcode.Incomplete, "vendor", "app/vendor/app.py  vendor"},
		{"nested third_party", map[string]string{"src/third_party/svc/app.py": "@flask"}, exitcode.Incomplete, "vendor", "src/third_party/svc/app.py  vendor"},
		{"nested venv", map[string]string{"services/venv/app.py": "@flask"}, exitcode.Incomplete, "vendor", "services/venv/app.py  vendor"},
		{"generated header", map[string]string{"app.py": generated + "@flask"}, exitcode.Incomplete, "generated", "app.py  generated"},
		// Evaluated: its sink is a finding. The Express app's NoSQL sink has no
		// reader class yet, which keeps that run incomplete on its own.
		{"min.js name", map[string]string{"app.min.js": "@express"}, exitcode.Incomplete, "unmapped_kind", "command_injection  app.min.js:"},
		{"root vendor tree", map[string]string{"app.py": "@flask", "vendor/lib/app.py": "@flask"}, exitcode.OK, "", "vendor/lib/app.py  vendor"},
		{"root node_modules", map[string]string{"app.py": "@flask", "node_modules/app/app.js": "@express"}, exitcode.OK, "", "node_modules/app/app.js  vendor"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			files := map[string]string{}
			for name, content := range tt.files {
				if body, ok := strings.CutPrefix(content, generated+"@"); ok {
					content = generated + testApp(t, body)
				}
				files[name] = content
			}
			cfg := scanRepo(t, files, "")
			m := &fakeModel{verdict: map[string]string{"command_injection": "vulnerable"}}
			code, out, errOut := runScanWith(fakeDeps(m, calibrate.TierM), "scan", "--config", cfg)
			if code != tt.wantCode {
				t.Fatalf("exit %d, want %d\n%s\n%s", code, tt.wantCode, out, errOut)
			}
			if tt.listed != "" && !strings.Contains(out, tt.listed) {
				t.Errorf("output lacks %q:\n%s", tt.listed, out)
			}
			checkJSONReport(t, tt.wantReason)
		})
	}
}
