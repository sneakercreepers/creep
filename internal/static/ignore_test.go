package static

import (
	"context"
	"strings"
	"testing"
)

const routeSrc = "from flask import Flask\napp = Flask(__name__)\n@app.get('/a')\ndef a():\n    db.execute(q)\n"

func TestIgnoreReason(t *testing.T) {
	longLine := strings.Repeat("var a=1;", 200)
	cases := []struct {
		name, path, src string
		want            Ignored
	}{
		{"plain app", "app/views.py", routeSrc, 0},
		{"vendor dir", "vendor/lib/app.py", routeSrc, IgnoredVendor},
		{"nested node_modules", "web/node_modules/x/index.js", "", IgnoredVendor},
		{"windows separators", `web\node_modules\x\index.js`, "", IgnoredVendor},
		{"case-insensitive dir", "Lib/Site-Packages/flask/app.py", routeSrc, IgnoredVendor},
		{"virtualenv", ".venv/lib/python3.12/m.py", "", IgnoredVendor},
		{"vendor as file name only", "src/vendor.py", routeSrc, 0},
		{"vendor-like dir name", "src/vendors/app.py", routeSrc, 0},
		{"go-style marker", "api/models.py", "# Code generated by tool. DO NOT EDIT.\n" + routeSrc, IgnoredGenerated},
		{"protoc marker", "api/x_pb2.py", "# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n", IgnoredGenerated},
		{"@generated", "gen/client.ts", "/**\n * @generated\n */\nexport {}\n", IgnoredGenerated},
		{"do not modify", "gen/c.js", "// This file was generated. Do not modify.\n", IgnoredGenerated},
		{"marker past the head", "app.py", strings.Repeat("x = 1\n", 200) + "# Code generated DO NOT EDIT.\n", 0},
		{"marker in a string, not a comment", "app.py", "s = 'generated, do not edit'\n" + routeSrc, 0},
		{"generated without do-not-edit", "app.py", "# Generated by Django 4.2\n" + routeSrc, 0},
		{"min.js name", "static/app.min.js", "a()\n", IgnoredMinified},
		{"-min.js name", "static/app-min.js", "a()\n", IgnoredMinified},
		{"long-line script", "static/bundle.js", longLine, IgnoredMinified},
		{"long-line typescript", "static/bundle.ts", longLine + "\n" + longLine, IgnoredMinified},
		{"minimal.js is not minified", "static/minimal.js", "a()\n", 0},
		{"short long-line script", "static/tiny.js", "var a=1;var b=2;", 0},
		{"long python line is parsed", "app.py", "x = '" + strings.Repeat("a", 4000) + "'\n", 0},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := IgnoreReason(c.path, []byte(c.src)); got != c.want {
				t.Errorf("IgnoreReason(%q) = %s, want %s", c.path, got, c.want)
			}
		})
	}
}

// TestIgnoredFileIsListedNotExtracted: a vendor or generated file is never
// silently dropped. It keeps a File entry with the reason and no routes,
// even when the caller parsed it and called AddPython anyway.
func TestIgnoredFileIsListedNotExtracted(t *testing.T) {
	cases := []struct {
		path, src string
		want      Ignored
	}{
		{"vendor/flask_app/app.py", routeSrc, IgnoredVendor},
		{"app/api.py", "# @generated by openapi-generator\n" + routeSrc, IgnoredGenerated},
		{"app/views.py", routeSrc, 0},
	}
	for _, c := range cases {
		t.Run(c.path, func(t *testing.T) {
			tree, err := testParser(t).Parse(context.Background(), Python, []byte(c.src))
			if err != nil {
				t.Fatal(err)
			}
			e := NewExtractor()
			if err := e.AddPython(c.path, tree, []byte(c.src)); err != nil {
				t.Fatal(err)
			}
			g := e.Graph()
			if len(g.Files) != 1 || g.Files[0].Ignored != c.want || e.Locations().Files[0] != c.path {
				t.Fatalf("files %+v locations %+v", g.Files, e.Locations().Files)
			}
			if routes := len(g.Routes); (routes == 0) != (c.want != 0) {
				t.Errorf("ignored=%s but %d routes", c.want, routes)
			}
		})
	}
}

func TestAddIgnored(t *testing.T) {
	e := NewExtractor()
	if err := e.AddIgnored("node_modules/x/index.js", IgnoredVendor); err != nil {
		t.Fatal(err)
	}
	if f := e.Graph().Files[0]; f.Language != JavaScript || f.Ignored != IgnoredVendor {
		t.Errorf("file %+v", f)
	}
	for _, bad := range []Ignored{0, IgnoredMinified + 1} {
		if err := e.AddIgnored("a.py", bad); err == nil {
			t.Errorf("reason %d accepted", bad)
		}
	}
	if len(e.Graph().Files) != 1 {
		t.Error("rejected reason was listed")
	}
	for r, want := range map[Ignored]string{0: "none", IgnoredVendor: "vendor", IgnoredGenerated: "generated", IgnoredMinified: "minified", 9: "unknown"} {
		if r.String() != want {
			t.Errorf("Ignored(%d) = %s, want %s", r, r, want)
		}
	}
}

// BenchmarkIgnoreReason: the check reads a bounded head plus one byte count,
// so it stays linear on a large file.
func BenchmarkIgnoreReason(b *testing.B) {
	src := []byte(strings.Repeat("x = 1\n", 1<<18))
	b.SetBytes(int64(len(src)))
	for b.Loop() {
		IgnoreReason("pkg/deep/app.js", src)
	}
}
