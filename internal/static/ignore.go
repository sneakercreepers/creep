package static

import (
	"bytes"
	"fmt"
	"path"
	"regexp"
	"strings"
)

// Ignored is why a file was listed but not evaluated. The zero value means
// the file was evaluated.
type Ignored uint8

// Reasons a file is not evaluated.
const (
	// IgnoredVendor: a path segment is a dependency directory
	// (vendorDirs).
	IgnoredVendor Ignored = iota + 1
	// IgnoredGenerated: a comment near the top marks the file as generated.
	IgnoredGenerated
	// IgnoredMinified: a JavaScript or TypeScript file named *.min.js or
	// whose average line is longer than minifiedLineBytes.
	IgnoredMinified
)

// String returns the reason name.
func (r Ignored) String() string {
	switch r {
	case 0:
		return "none"
	case IgnoredVendor:
		return "vendor"
	case IgnoredGenerated:
		return "generated"
	case IgnoredMinified:
		return "minified"
	}
	return "unknown"
}

// vendorDirs are directory names that hold third-party code, compared
// without case because the scanned repo may come from a case-insensitive
// file system.
var vendorDirs = []string{
	"vendor", "node_modules", "bower_components", "jspm_packages", "third_party",
	"site-packages", "dist-packages", "__pypackages__", ".venv", "venv",
}

const (
	// generatedHeadBytes bounds the generated-marker search, so the check
	// costs the same on any file and a marker deep in a file (a string in
	// code) does not count.
	generatedHeadBytes = 1024
	// minifiedLineBytes is the average line length past which a script is
	// treated as minified; hand-written code stays far below it.
	minifiedLineBytes = 500
	minifiedMinBytes  = 1024
)

// IgnoreReason reports why the file with contents src should not be parsed,
// or 0 when it should. name must be relative to the repository root
// (slash- or backslash-separated): directories above the root must not
// decide what is skipped, so an absolute or escaping name is an error.
// Callers check it before parsing and record a non-zero reason with
// Extractor.AddIgnored, so the file is listed as not evaluated rather than
// dropped.
func IgnoreReason(name string, src []byte) (Ignored, error) {
	rel, err := repoRelative(name)
	if err != nil {
		return 0, err
	}
	lang, _ := LanguageForPath(rel)
	switch {
	case inVendorDir(rel):
		return IgnoredVendor, nil
	case hasGeneratedMarker(lang, src):
		return IgnoredGenerated, nil
	case minified(rel, src):
		return IgnoredMinified, nil
	}
	return 0, nil
}

// repoRelative normalizes a repo-relative name to a clean slash path.
func repoRelative(name string) (string, error) {
	slash := strings.ReplaceAll(name, "\\", "/")
	clean := path.Clean(slash)
	switch {
	case slash == "" || clean == ".":
		return "", fmt.Errorf("path %q: empty", name)
	case strings.HasPrefix(slash, "/") || (len(slash) > 1 && slash[1] == ':'):
		return "", fmt.Errorf("path %q: not relative to the repository root", name)
	case clean == ".." || strings.HasPrefix(clean, "../"):
		return "", fmt.Errorf("path %q: escapes the repository root", name)
	}
	return clean, nil
}

func inVendorDir(name string) bool {
	dirs := strings.Split(path.Dir(name), "/")
	for _, d := range dirs {
		for _, v := range vendorDirs {
			if strings.EqualFold(d, v) {
				return true
			}
		}
	}
	return false
}

// goGenerated is Go's convention (go help generate), which many generators
// for other languages follow too.
var goGenerated = regexp.MustCompile(`^Code generated .* DO NOT EDIT\.$`)

// hasGeneratedMarker reports whether a comment in the leading comment block
// of the file carries an established generator marker, matched exactly:
// "Code generated ... DO NOT EDIT.", "@generated" as the first word, or
// protoc's header. Strings, docstrings and comments after the first line of
// code never count, so a loose mention cannot hide a file.
func hasGeneratedMarker(lang Language, src []byte) bool {
	for _, c := range leadingComments(lang, src) {
		switch {
		case goGenerated.MatchString(c),
			c == "@generated" || strings.HasPrefix(c, "@generated "),
			strings.HasPrefix(c, "Generated by the protocol buffer compiler.") && strings.Contains(c, "DO NOT EDIT!"):
			return true
		}
	}
	return false
}

// leadingComments returns the text of the comments before the first line of
// code in the first generatedHeadBytes, without comment syntax. Python
// comments start with '#'; other files use '//', '/* ... */' and a '#!'
// first line.
func leadingComments(lang Language, src []byte) []string {
	head := bytes.TrimPrefix(src[:min(len(src), generatedHeadBytes)], []byte{0xef, 0xbb, 0xbf}) // UTF-8 BOM
	var out []string
	inBlock := false
	for i, raw := range strings.Split(string(head), "\n") {
		line := strings.TrimSpace(raw)
		switch {
		case inBlock:
		case line == "":
			continue
		case lang == Python || (i == 0 && strings.HasPrefix(line, "#!")):
			if !strings.HasPrefix(line, "#") {
				return out
			}
			out = append(out, strings.TrimSpace(line[1:]))
			continue
		case strings.HasPrefix(line, "//"):
			out = append(out, strings.TrimSpace(line[2:]))
			continue
		case strings.HasPrefix(line, "/*"):
			inBlock, line = true, line[2:]
		default:
			return out
		}
		body, rest, closed := strings.Cut(line, "*/")
		out = append(out, strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(body), "*")))
		if closed {
			inBlock = false
			if strings.TrimSpace(rest) != "" {
				return out
			}
		}
	}
	return out
}

// minified applies only to scripts: Python is never minified in practice,
// so a long Python line is parsed, not skipped.
func minified(name string, src []byte) bool {
	lang, ok := LanguageForPath(name)
	if !ok || lang == Python {
		return false
	}
	base := strings.ToLower(path.Base(name))
	stem := strings.TrimSuffix(base, path.Ext(base))
	if strings.HasSuffix(stem, ".min") || strings.HasSuffix(stem, "-min") {
		return true
	}
	lines := bytes.Count(src, []byte("\n")) + 1
	return len(src) >= minifiedMinBytes && len(src)/lines > minifiedLineBytes
}

// AddIgnored lists a file that was not evaluated, with the reason, so the
// report can show it as not covered. path is kept only in Locations.
func (e *Extractor) AddIgnored(name string, why Ignored) error {
	if why == 0 || why > IgnoredMinified {
		return fmt.Errorf("ignore %s: invalid reason %d", name, why)
	}
	if !fits(len(e.graph.Files) + 1) {
		return fmt.Errorf("ignore %s: %w", name, ErrGraphFull)
	}
	rel, err := repoRelative(name)
	if err != nil {
		return fmt.Errorf("ignore: %w", err)
	}
	lang, _ := LanguageForPath(rel)
	id := FileID(len(e.graph.Files)) //nolint:gosec // G115: fits checked above
	e.graph.Files = append(e.graph.Files, File{ID: id, Language: lang, Ignored: why})
	e.locs.Files = append(e.locs.Files, name)
	return nil
}
